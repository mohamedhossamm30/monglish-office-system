function parseItems() {
  const lines = itemsRaw.trim().split('\n');
  const items = [];
  let idx = 1;

  for (const line of lines) {
    if (!line.trim()) continue;
    const parts = line.split(',');
    const name = parts[0]?.trim();
    const catName = parts[1]?.trim();
    const code = parts[2]?.trim();
    const unit = parts[3]?.trim() || 'عدد';
    const initialBal = parseFloat(parts[4]) || 0;
    const qtyIn = parseFloat(parts[5]) || 0;
    const qtyOut = parseFloat(parts[6]) || 0;
    const remBal = parseFloat(parts[7]) || 0;
    const note = parts[8]?.trim() || '';

    if (!code) continue;

    let catKey = 'OFF';
    if (catName === 'ادوات مكتبية') catKey = 'OFF';
    else if (catName === 'ادوية') catKey = 'MED';
    else if (catName === 'الكترونيات') catKey = 'ELEC';
    else if (catName === 'بوفيه') catKey = 'BUFF';
    else if (catName === 'نظافة') catKey = 'CLN';

    // Approximate unit cost based on category and type
    let cost = 25;
    if (catKey === 'ELEC') {
      if (name.includes('لاب توب')) cost = 12000;
      else if (name.includes('موبايل')) cost = 5500;
      else if (name.includes('شاشة')) cost = 3000;
      else if (name.includes('كاميرا')) cost = 1200;
      else if (name.includes('سماعة')) cost = 650;
      else if (name.includes('راوتر') || name.includes('سويتش')) cost = 850;
      else if (name.includes('ماووس') || name.includes('كيبورد')) cost = 120;
      else if (name.includes('شاحن') || name.includes('كابل')) cost = 95;
      else cost = 250;
    } else if (catKey === 'BUFF') {
      if (name.includes('بن')) cost = 420;
      else if (name.includes('نسكافيه')) cost = 280;
      else if (name.includes('سكر')) cost = 30;
      else if (name.includes('لبن')) cost = 40;
      else if (name.includes('اكواب')) cost = 1.2;
      else if (name.includes('عصير') || name.includes('ايس كريم')) cost = 175;
      else cost = 45;
    } else if (catKey === 'CLN') {
      if (name.includes('ديتول') || name.includes('معطر')) cost = 85;
      else if (name.includes('مناديل')) cost = 65;
      else if (name.includes('كلور') || name.includes('فنيك')) cost = 35;
      else cost = 40;
    } else if (catKey === 'OFF') {
      if (name.includes('ورق تصوير') || name.includes('رزمة')) cost = 135;
      else if (name.includes('احبار')) cost = 350;
      else if (name.includes('كرسى')) cost = 2500;
      else if (name.includes('قلم')) cost = 8;
      else cost = 25;
    }

    // Determine healthy min threshold
    let min = 5;
    if (name.includes('ورق تصوير') || name.includes('اكواب') || name.includes('مناديل') || name.includes('سكر')) {
      min = 15;
    } else if (name.includes('لاب توب') || name.includes('طابعة') || name.includes('سنترال')) {
      min = 1;
    }

    items.push({
      id: 'item_' + (idx++),
      code,
      name,
      cat: catKey,
      unit,
      balance: remBal,
      min,
      cost,
      note: note || undefined
    });
  }

  return items;
}

